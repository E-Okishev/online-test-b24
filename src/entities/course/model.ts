export type Lesson = {
  id: string;
  title: string;
  theory: string;
  questions: [
    { type: "single"; text: string; options: string[]; correct: number },
    { type: "multiple"; text: string; options: string[]; correct: number[] },
    { type: "text"; text: string },
  ];
};

export type CourseId = "messenger" | "feed" | "calendar" | "drive" | "tasks";
export type Course = { id: CourseId; title: string; lessons: Lesson[] };

function lesson(id: string, title: string, theory: string, concept: string, actions: [string, string, string]): Lesson {
  return {
    id,
    title,
    theory,
    questions: [
      { type: "single", text: `Что главное в теме «${title}»?`, options: [concept, "Случайное удаление данных", "Изменение дизайна портала", "Отключение уведомлений для всех"], correct: 0 },
      { type: "multiple", text: "Какие действия относятся к этому уроку?", options: [...actions, "Передать пароль коллеге", "Удалить рабочую историю", "Игнорировать права доступа"], correct: [0, 1, 2] },
      { type: "text", text: `Кратко опишите, как вы примените тему «${title}» в своей работе.` },
    ],
  };
}

